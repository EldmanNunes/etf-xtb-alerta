import streamlit as st
import yfinance as yf
import pandas as pd
import plotly.graph_objects as go
from plotly.subplots import make_subplots

st.set_page_config(page_title="ETF Tracker XTB", layout="wide")
st.title("📊 ETF Tracker XTB")

ETF_MAP = {
    "PRAB - Amundi 0-1Y": "PRAB.DE",
    "XDEQ - World Quality": "XDEQ.DE",
    "IBCI - Inflation Linked": "IBCI.DE"
}

# Sidebar
st.sidebar.header("Configurações")
etfs_selecionados = st.sidebar.multiselect(
    "Selecione os ETFs:",
    options=list(ETF_MAP.keys()),
    default=list(ETF_MAP.keys())
)
periodo = st.sidebar.selectbox("Período:", ["1y", "2y", "5y", "10y", "max"], index=2)
ma_curta = st.sidebar.slider("Média Móvel Curta:", 10, 100, 50)
ma_longa = st.sidebar.slider("Média Móvel Longa:", 100, 300, 200)

@st.cache_data(ttl=3600)
def carregar_dados(tickers, p):
    df = yf.download(tickers, period=p, auto_adjust=True, progress=False)['Close']
    return df

if etfs_selecionados:
    tickers = [ETF_MAP[k] for k in etfs_selecionados]
    data = carregar_dados(tickers, periodo)

    # Métricas no topo
    cols = st.columns(len(etfs_selecionados))
    for i, nome in enumerate(etfs_selecionados):
        ticker = ETF_MAP[nome]
        if ticker in data.columns:
            serie = data[ticker].dropna()
            preco_atual = serie.iloc[-1]
            var_diaria = ((serie.iloc[-1] / serie.iloc[-2]) - 1) * 100
            cols[i].metric(label=nome, value=f"€{preco_atual:.2f}", delta=f"{var_diaria:+.2f}%")

    # Gráfico individual para cada ETF
    for nome in etfs_selecionados:
        ticker = ETF_MAP[nome]
        if ticker not in data.columns:
            continue

        serie = data[ticker].dropna()
        df_etf = pd.DataFrame({'Close': serie})
        df_etf['MA_Curta'] = df_etf['Close'].rolling(ma_curta).mean()
        df_etf['MA_Longa'] = df_etf['Close'].rolling(ma_longa).mean()

        # Cálculo do RSI (14)
        delta = df_etf['Close'].diff()
        gain = (delta.where(delta > 0, 0)).rolling(14).mean()
        loss = (-delta.where(delta < 0, 0)).rolling(14).mean()
        rs = gain / loss
        df_etf['RSI'] = 100 - (100 / (1 + rs))

        fig = make_subplots(rows=2, cols=1, shared_xaxes=True, vertical_spacing=0.08, row_heights=[0.7, 0.3])

        # Preço e MTMs
        fig.add_trace(go.Scatter(x=df_etf.index, y=df_etf['Close'], name="Preço (€)", line=dict(color='blue')), row=1, col=1)
        fig.add_trace(go.Scatter(x=df_etf.index, y=df_etf['MA_Curta'], name=f"MA {ma_curta}", line=dict(color='orange')), row=1, col=1)
        fig.add_trace(go.Scatter(x=df_etf.index, y=df_etf['MA_Longa'], name=f"MA {ma_longa}", line=dict(color='purple')), row=1, col=1)

        # RSI
        fig.add_trace(go.Scatter(x=df_etf.index, y=df_etf['RSI'], name="RSI (14)", line=dict(color='green')), row=2, col=1)
        fig.add_hline(y=70, line_dash="dash", line_color="red", row=2, col=1)
        fig.add_hline(y=30, line_dash="dash", line_color="green", row=2, col=1)

        fig.update_layout(title_text=f"Análise Técnica - {nome}", height=550)
        st.plotly_chart(fig, use_container_width=True)

    # Matriz de Correlação
    if len(etfs_selecionados) > 1:
        st.subheader("Matriz de Correlação dos Retornos Diários")
        retornos = data.pct_change().dropna()
        st.dataframe(retornos.corr().style.background_gradient(cmap="Blues"))

    # Download CSV
    csv = data.to_csv().encode('utf-8')
    st.download_button("📥 Descarregar Dados Históricos (CSV)", data=csv, file_name="etfs_xtb_historico.csv", mime="text/csv")